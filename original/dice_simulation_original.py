    fig, ax = plt.subplots(figsize=(10, 6))
    # Plot each line by number of sides
    for sides, config_df in group_df.groupby('Sides'):
        config_df = config_df.sort_values(by='Trials')
        color = side_colors.get(sides, 'gray')
        ax.plot(config_df['Trials'], config_df['Deviation'],
                marker='o', linestyle='-', color=color,
                label=f'Deviation ({sides} sides)')
        # Annotate each point above its value (use * for scale)
        for x, y in zip(config_df['Trials'], config_df['Deviation']):
            if y > 0:
                ax.text(x, y * 1.15, f'{y:.4f}', ha='center', va='bottom', fontsize=8)
    # Add reference line at y = 0 (horizontal guide)
    ax.axhline(0, color='gray', linestyle='dashed', linewidth=1)
    # Set log-log scale
    ax.set_xscale('log')
    ax.set_yscale('log')
    ax.set_xlabel('Number of Trials (log scale)')
    ax.set_ylabel('Deviation (log scale)')
    ax.set_title(f'Deviation Between Simulated and Expected Value\n({dice} dice)')
    # Adjust y-limits dynamically for each plot
    all_devs = group_df['Deviation'].values
    all_devs = [dev for dev in all_devs if dev > 0]
    if all_devs:
        y_min = min(all_devs)
        y_max = max(all_devs)
        ax.set_ylim(y_min * 0.8, y_max * 1.5)
    else:
        ax.set_ylim(1e-3, 1)  # Default range if no valid values
    # Grid and legend outside
    ax.grid(True, which='both', linestyle='--', alpha=0.7)
    ax.legend(loc='center left', bbox_to_anchor=(1, 0.5), fontsize=9)
    # Use tight layout
    plt.tight_layout()
    plt.show()
