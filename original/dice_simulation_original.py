# Commented out IPython magic to ensure Python compatibility.
import random
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from itertools import product
from collections import Counter
# Enable inline plots
# %matplotlib inline
"""## Define the Dice Roll Simulation Function"""
def roll_dice(num_sides, num_dice, num_trials):
    results = [sum(random.randint(1, num_sides) for _ in range(num_dice)) for _ in range(num_trials)]
    simulated_mean = np.mean(results)
    expected_value = num_dice * (num_sides + 1) / 2
    deviation = abs(simulated_mean - expected_value)
    return {
        'num_sides': num_sides,
        'num_dice': num_dice,
        'num_trials': num_trials,
        'simulated_mean': simulated_mean,
        'expected_value': expected_value,
        'deviation': deviation,
        'all_rolls': results
    }
"""## Define Configurations & Run Simulations"""
# Settings
dice_sides = [4, 6, 8, 10, 12, 20]
dice_counts = [1, 2, 3, 4, 5]
trial_counts = [10, 100, 1000, 10000, 100000]
# Storage
results_summary = []
sample_histograms = []
# Run simulations
for num_sides, num_dice, num_trials in product(dice_sides, dice_counts, trial_counts):
    result = roll_dice(num_sides, num_dice, num_trials)
    results_summary.append({
        'Sides': result['num_sides'],
        'Dice': result['num_dice'],
        'Trials': result['num_trials'],
        'Simulated Mean': result['simulated_mean'],
        'Expected Value': result['expected_value'],
        'Deviation': result['deviation']
    })
    # Save data for histogram
    if num_trials == 10000 and (num_dice, num_sides) in [(1, 20), (2, 12), (3, 8), (4, 6), (5, 4)]:
        sample_histograms.append({
            'label': f'{num_dice}d{num_sides} - {num_trials} trials',
            'data': result['all_rolls']
        })
# Convert to DataFrame
summary_df = pd.DataFrame(results_summary)
summary_df.head()
# Export the full summary to CSV
summary_df.to_csv('dice_roll_summary.csv', index=False)
"""## Plot Histograms of Select Configurations"""
# Define the selected configurations explicitly
selected_configs = [
    (1, 20),
    (2, 12),
    (3, 8),
    (4, 6),
    (5, 4),
]
# Plot histograms for each selected configuration
for config in selected_configs:
    dice, sides = config
    trial_count = 10000  # Use 10,000 trials for stable histograms
    # Find matching histogram data
    for hist in sample_histograms:
        if hist['label'].startswith(f"{dice}d{sides}") and f"{trial_count}" in hist['label']:
            data = hist['data']
            formatted_label = f"{dice} dice {sides} sides"
            # Count outcomes
            outcome_counts = Counter(data)
            outcomes = sorted(outcome_counts.keys())
            frequencies = [outcome_counts[o] for o in outcomes]
            # Plotting
            plt.figure(figsize=(10, 5))
            plt.bar(outcomes, frequencies, color='skyblue', edgecolor='black')
            plt.title(f'Distribution of Outcomes\n{formatted_label}')
            plt.xlabel('Sum of Dice Rolls')
            plt.ylabel('Frequency')
            plt.xticks(outcomes)
            plt.grid(axis='y', linestyle='--', alpha=0.7)
            plt.tight_layout()
            plt.show()
"""## Line Plot: Simulated Mean vs Expected Value"""
# Updated Simulated Mean vs Expected Value plots: grouped by dice, one figure per dice value
# Define colors by number of sides
side_colors = {
    4: 'blue',
    6: 'green',
    8: 'purple',
    10: 'orange',
    12: 'brown',
    20: 'black'
}
# Create one plot for each number of dice (1 through 5)
for dice in sorted(summary_df['Dice'].unique()):
    fig, ax = plt.subplots(figsize=(10, 6))
    for sides in sorted(summary_df['Sides'].unique()):
        config_df = summary_df[(summary_df['Dice'] == dice) & (summary_df['Sides'] == sides)]
        if config_df.empty:
            continue
        config_df = config_df.sort_values(by='Trials')
        expected = config_df['Expected Value'].iloc[0]
        final_trial = config_df['Trials'].iloc[-1]
        color = side_colors.get(sides, 'gray')
        # Plot simulated mean line
        ax.plot(config_df['Trials'], config_df['Simulated Mean'], marker='o',
                color=color, label=f'Simulated Mean ({sides} sides)')
        # Plot expected value line
        ax.axhline(y=expected, color=color, linestyle='--', linewidth=1.5,
                   label=f'Expected Value ({sides} sides)')
        # Annotate each point with simulated mean
        for x, y in zip(config_df['Trials'], config_df['Simulated Mean']):
            offset = 0.3 if y < expected else -0.3
            ax.text(x, y + offset, f'{y:.2f}', ha='center', va='bottom', fontsize=8)
    # Final formatting
    ax.set_xscale('log')
    ax.set_ylim(bottom=0)  # Ensure all plots stay in view
    ax.set_title(f'Simulated Mean vs Expected Value\n({dice} dice)')
    ax.set_xlabel('Number of Trials')
    ax.set_ylabel('Simulated Mean')
    ax.legend(loc='center left', bbox_to_anchor=(1, 0.5), fontsize=9)
    ax.grid(True, which='both', linestyle='--', alpha=0.7)
    plt.tight_layout()
    plt.show()
